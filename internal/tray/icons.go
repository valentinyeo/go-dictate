func getIconData(color string) []byte {
	switch color {
	case "blue":
		return createColoredIcon(0x00, 0x78, 0xD4) // #0078D4 Microsoft Blue
	case "red":
		return createColoredIcon(0xD1, 0x34, 0x38) // #D13438 Red
	default: // grey
		return createColoredIcon(0x8A, 0x8A, 0x8A) // #8A8A8A Grey
	}
}

// Create a simple 16x16 ICO with a colored circle
func createColoredIcon(r, g, b byte) []byte {
	const size = 16
	const headerSize = 22

	// ICO file header
	icon := []byte{
		0x00, 0x00, // Reserved
		0x01, 0x00, // Type: ICO
		0x01, 0x00, // Number of images: 1

		// Image directory entry
		byte(size), // Width
		byte(size), // Height
		0x00,       // Color palette (0 = no palette)
		0x00,       // Reserved
		0x01, 0x00, // Color planes
		0x20, 0x00, // Bits per pixel (32-bit)
		0x00, 0x00, 0x00, 0x00, // Size of image data (filled below)
		byte(headerSize), 0x00, 0x00, 0x00, // Offset to image data
	}

	// BMP header
	bmpHeader := []byte{
		0x28, 0x00, 0x00, 0x00, // Header size (40 bytes)
		byte(size), 0x00, 0x00, 0x00, // Width
		byte(size * 2), 0x00, 0x00, 0x00, // Height (double for AND mask)
		0x01, 0x00, // Color planes
		0x20, 0x00, // Bits per pixel
		0x00, 0x00, 0x00, 0x00, // Compression (none)
		0x00, 0x00, 0x00, 0x00, // Image size (0 for uncompressed)
		0x00, 0x00, 0x00, 0x00, // X pixels per meter
		0x00, 0x00, 0x00, 0x00, // Y pixels per meter
		0x00, 0x00, 0x00, 0x00, // Colors used
		0x00, 0x00, 0x00, 0x00, // Important colors
	}

	icon = append(icon, bmpHeader...)

	// Create pixel data (16x16 RGBA, drawn as a circle)
	center := float64(size) / 2.0
	radius := center - 2.0

	// Pixels are stored bottom-up in BMP
	for y := size - 1; y >= 0; y-- {
		for x := 0; x < size; x++ {
			dx := float64(x) - center
			dy := float64(y) - center
			dist := dx*dx + dy*dy

			var pixel [4]byte
			if dist <= radius*radius {
				// Inside circle - use color
				pixel = [4]byte{b, g, r, 0xFF} // BGRA format
			} else {
				// Outside circle - transparent
				pixel = [4]byte{0x00, 0x00, 0x00, 0x00}
			}
			icon = append(icon, pixel[:]...)
		}
	}

	// AND mask (all zeros for transparency support)
	maskSize := size * size / 8
	if size*size%8 != 0 {
		maskSize++
	}
	// Pad to 4-byte boundary
	rowSize := (size + 31) / 32 * 4
	for y := 0; y < size; y++ {
		for x := 0; x < rowSize; x++ {
			icon = append(icon, 0x00)
		}
	}

	// Update size in header
	imageSize := len(icon) - headerSize
	icon[14] = byte(imageSize & 0xFF)
	icon[15] = byte((imageSize >> 8) & 0xFF)
	icon[16] = byte((imageSize >> 16) & 0xFF)
	icon[17] = byte((imageSize >> 24) & 0xFF)

	return icon
}
